import { StateGraph, StateSchema, type GraphNode, START, END } from "@langchain/langgraph";
import z from "zod";
import { cohereModel, geminiModel, groqModel } from "./models.service.js";
import { createAgent, HumanMessage, providerStrategy } from "langchain";

const state = new StateSchema({
    problem: z.string().default(""),
    solution_1: z.string().default(""),
    solution_2: z.string().default(""),
    judgement: z.object({
        solution_1: z.object({
            score: z.number().default(0),
            feedback: z.string().default(""),
        }),
        solution_2: z.object({
            score: z.number().default(0),
            feedback: z.string().default(""),
        }),
        winner: z.string().default("")
    }).default({
        solution_1: { score: 0, feedback: "" },
        solution_2: { score: 0, feedback: "" },
        winner: ""
    })
});

const solutionNode: GraphNode<typeof state> = async (state) => {
    const [groqResponse, cohereResponse] = await Promise.all([
        groqModel.invoke(state.problem),
        cohereModel.invoke(state.problem)
    ]);

    return {
        solution_1: groqResponse.text,
        solution_2: cohereResponse.text
    }
}

const judgeNode: GraphNode<typeof state> = async (state) => {
    const {problem, solution_1, solution_2} = state;

    const aiJudge = createAgent({
        model: geminiModel,
        tools: [],
        responseFormat: providerStrategy(z.object({
            solution_1: z.object({
                score: z.number().min(0).max(10),
                feedback: z.string()
            }),
            solution_2: z.object({
                score: z.number().min(0).max(10),
                feedback: z.string()
            }),
            winner: z.string()
        })),
        systemPrompt: `You are a judge tasked with evaluating two solutions generated by two different AI models. Please provide a score out of 10 for each solution, along with feedback for each scores.`
    });

    const judgeResponse = await aiJudge.invoke({
        messages: [
            new HumanMessage(`
            Problem: ${problem}
            Solution 1: ${solution_1}
            Solution 2: ${solution_2}
            Please evaluate the two solutions and provide scores and feedback
                `)
        ]
    })

    const solution_1_judgement = judgeResponse.structuredResponse.solution_1;

    const solution_2_judgement = judgeResponse.structuredResponse.solution_2;

    const winner = judgeResponse.structuredResponse.winner;

    return {
        judgement: {
            solution_1: solution_1_judgement,
            solution_2: solution_2_judgement,
            winner
        }
    }
}

const graph = new StateGraph(state)
   .addNode("solution", solutionNode)
   .addNode("judge_node", judgeNode)
   .addEdge(START, "solution")
   .addEdge("solution", "judge_node")
   .addEdge("judge_node", END)
   .compile()

export default async function runGraph(problem: string) {
    const result = await graph.invoke({
        problem
    });

    return result;
};   